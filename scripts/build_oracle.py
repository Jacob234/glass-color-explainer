"""Build test/fixtures/colour-science.json: reference colors from colour-science, for npm test.

The site's color engine (optics-core.js, spectra.js) is hand-written. This script recomputes the
same quantities with colour-science, the reference Python implementation of CIE colorimetry, so
test/oracle.test.mjs can check the engine against it. Not run by the site build or by npm test;
rerun it only when the inputs or the colour-science version change.

    python3 -m pip install colour-science==0.4.7
    python3 scripts/build_oracle.py > test/fixtures/colour-science.json

What differs on purpose between the two:
- Observer. The engine uses Wyman, Sloan & Shirley's analytic fit to the CIE 1931 2° functions;
  the oracle uses colour-science's copy of the CIE table at 5 nm. This is the main source of
  difference, and what the test tolerances budget for.
- Everything else is meant to agree: Riemann sum on the same 5 nm grid (colour-science's
  'Integration' method, not the ASTM E308 weighting tables), Y of the illuminant's white = 1,
  von Kries adaptation in Bradford space to D65, and IEC 61966-2-1 sRGB.

The transmission spectra come from scripts/oracle_inputs.mjs (the site's own densities, so the
fixture covers what the page draws); the lamp spectra come from colour-science, not lamps.json,
so the test also exercises the engine on independent illuminant data.
"""
import json
import subprocess
import sys
from pathlib import Path

import colour
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SHAPE = colour.SpectralShape(380, 780, 5)
GRID = np.arange(380, 781, 5)

CMFS = colour.MSDS_CMFS['CIE 1931 2 Degree Standard Observer'].copy().align(SHAPE)
assert np.array_equal(CMFS.wavelengths, GRID)
D65_XY = colour.CCS_ILLUMINANTS['CIE 1931 2 Degree Standard Observer']['D65']
D65_XYZ = colour.xy_to_XYZ(D65_XY)


def sd(values):
    return colour.SpectralDistribution(dict(zip(GRID, values)))


def tristimulus(spectrum):
    """Unnormalized XYZ of a spectrum on GRID: sum of S(λ)·x̄(λ)·Δλ, with k = 1."""
    return colour.sd_to_XYZ(sd(spectrum), CMFS, method='Integration', k=1)


def blackbody(T):
    return colour.colorimetry.planck_law(GRID * 1e-9, T)


def rounded(a, digits=8):
    return [float(f'{v:.{digits}g}') for v in np.atleast_1d(a)]


# Lamps, from colour-science's tables (CIE 15:2018) or Planck's law.
LAMPS = {
    'D65': colour.SDS_ILLUMINANTS['D65'].copy().align(SHAPE).values,
    'A': colour.SDS_ILLUMINANTS['A'].copy().align(SHAPE).values,
    'FL11': colour.SDS_ILLUMINANTS['FL11'].copy().align(SHAPE).values,
    'LED-B3': colour.SDS_ILLUMINANTS['LED-B3'].copy().align(SHAPE).values,
    'blackbody-1850': blackbody(1850),
}
LAMPS = {k: v / v.max() for k, v in LAMPS.items()}


def seen(T, spd, adapt):
    """XYZ (white Y = 1) of transmission T under spd: adapted to D65 when adapt, else as is."""
    white = tristimulus(spd)
    xyz = tristimulus(spd * T) / white[1]
    if adapt:
        xyz = colour.adaptation.chromatic_adaptation_VonKries(xyz, white / white[1], D65_XYZ, transform='Bradford')
    return xyz


def entry(xyz):
    lab = colour.XYZ_to_Lab(xyz, D65_XY)
    rgb = colour.XYZ_to_sRGB(xyz, D65_XY, apply_cctf_encoding=False)
    return {'XYZ': rounded(xyz), 'Lab': rounded(lab), 'linearRGB': rounded(rgb)}


inputs = json.loads(subprocess.run(['node', str(ROOT / 'scripts/oracle_inputs.mjs')], capture_output=True, text=True, check=True).stdout)
assert inputs['grid'] == GRID.tolist()

samples = []
for s in inputs['samples']:
    T = np.array(s['T'])
    samples.append({
        'id': s['id'], 'T': s['T'],
        'adapted': {lamp: entry(seen(T, spd, True)) for lamp, spd in LAMPS.items()},
        'unadapted': {lamp: entry(seen(T, spd, False)) for lamp, spd in LAMPS.items()},
    })

# optics-core.js works on optics.json's own 25 nm samples, interpolated linearly to 5 nm in
# optical density. The oracle does the same interpolation (np.interp), then the same colorimetry.
optics = json.loads((ROOT / 'src/data/optics.json').read_text())
W = np.array(optics['wavelengths'])
coarse = []
for c in optics['colorants']:
    density = -np.log10(1 - np.clip(c['absorbance'], 0, 0.999))
    T = 10 ** -np.interp(GRID, W, density)
    for il in optics['illuminants']:
        spd = np.interp(GRID, W, il['spd'])
        coarse.append({'colorant': c['id'], 'illuminant': il['id'], **entry(seen(T, spd, True))})

fixture = {
    '_note': 'Generated by scripts/build_oracle.py with colour-science ' + colour.__version__ + '. Do not edit by hand.',
    'colourScience': colour.__version__,
    'grid': GRID.tolist(),
    'whiteD65': rounded(D65_XYZ),
    'cmf': [rounded(row) for row in CMFS.values],
    'srgbMatrix': [rounded(row) for row in colour.RGB_COLOURSPACES['sRGB'].matrix_XYZ_to_RGB],
    'bradford': [rounded(row) for row in colour.adaptation.CAT_BRADFORD],
    'lamps': {k: {'spd': rounded(v), 'xy': rounded(colour.XYZ_to_xy(tristimulus(v)))} for k, v in LAMPS.items()},
    'blackbody': [{'T': T, 'xy': rounded(colour.XYZ_to_xy(tristimulus(blackbody(T))))} for T in (800, 1000, 1423, 1850, 2856, 6500)],
    'samples': samples,
    'coarse': coarse,
}
json.dump(fixture, sys.stdout, separators=(',', ':'))
print()
